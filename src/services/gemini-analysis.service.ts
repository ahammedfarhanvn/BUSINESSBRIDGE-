/**
 * Standard error class for Gemini analysis service errors with HTTP status codes.
 */
export class AnalysisServiceError extends Error {
  statusCode: number;

  constructor(message: string, statusCode: number = 500) {
    super(message);
    this.name = "AnalysisServiceError";
    this.statusCode = statusCode;
  }
}

const RISK_ASSESSMENT_DISCLAIMER =
  "This risk assessment is generated by AI based on current milestone due dates, task backlogs, and mentor feedback. Review with your advisory board.";

interface GeminiProgressSummaryResult {
  summary: string;
  key_accomplishments: string[];
  immediate_focuses: string[];
}

interface GeminiRiskResult {
  overall_risk_level: "low" | "medium" | "high";
  risks: Array<{
    id?: string;
    title: string;
    description: string;
    severity: "low" | "medium" | "high";
    category:
      | "overdue_milestone"
      | "incomplete_critical_task"
      | "launch_delay"
      | "unaddressed_feedback"
      | "operational";
    supporting_references?: Array<{
      type: "milestone" | "task" | "feedback" | "project";
      id: string;
      title: string;
    }>;
    suggested_mitigation: string;
  }>;
  launch_delay_risk?: {
    is_at_risk?: boolean;
    projected_delay_days?: number;
    rationale?: string;
  };
}

/**
 * Helper to fetch and verify access to a startup project.
 * Verifies that the project belongs to the founder (founder_id = founderUserId)
 * or user has authorized administrative / board advisory privileges.
 */
async function fetchAuthorizedProject(
  founderUserId: string,
  projectId?: string
): Promise<StartupProjectRecord> {
  const supabase = await createClient();

  if (projectId) {
    const { data: project, error: pError } = await supabase
      .from("startup_projects")
      .select("*")
      .eq("id", projectId)
      .maybeSingle();

    if (pError) {
      throw new AnalysisServiceError(`Failed to fetch project: ${pError.message}`, 500);
    }

    if (!project) {
      throw new AnalysisServiceError("Project not found.", 404);
    }

    if (project.founder_id !== founderUserId) {
      // Check if user is an admin or authorized board member
      const { data: profile } = await supabase
        .from("profiles")
        .select("role")
        .eq("id", founderUserId)
        .maybeSingle();

      const isAdmin = profile?.role === "admin";
      if (!isAdmin) {
        const { data: boardMembership } = await supabase
          .from("board_members")
          .select("id")
          .eq("founder_id", project.founder_id)
          .eq("membership_status", "active")
          .eq("mentor_id", founderUserId)
          .maybeSingle();

        if (!boardMembership) {
          throw new AnalysisServiceError(
            "Forbidden: You do not have access to this project.",
            403
          );
        }
      }
    }

    return project as StartupProjectRecord;
  }

  // If no projectId provided, fetch founder's active or most recent project
  const { data: projects, error: pListError } = await supabase
    .from("startup_projects")
    .select("*")
    .eq("founder_id", founderUserId)
    .order("created_at", { ascending: false });

  if (pListError) {
    throw new AnalysisServiceError(`Failed to fetch projects: ${pListError.message}`, 500);
  }

  if (!projects || projects.length === 0) {
    throw new AnalysisServiceError("No projects found for this founder.", 404);
  }

  const activeProject = projects.find((p) => p.status === "active") || projects[0];
  return activeProject as StartupProjectRecord;
}

/**
 * Generates an executive progress summary for a startup project.
 *
 * @param founderUserId The authenticated founder user ID
 * @param projectId Optional project ID; defaults to founder's active project
 * @returns ProgressSummaryResponse
 */
export async function generateProgressSummary(
  founderUserId: string,
  projectId?: string
): Promise<ProgressSummaryResponse> {
  const supabase = await createClient();
  const project = await fetchAuthorizedProject(founderUserId, projectId);

  // 1. Fetch Milestones ordered by sort_order
  const { data: rawMilestones, error: mError } = await supabase
    .from("project_milestones")
    .select("*")
    .eq("project_id", project.id)
    .order("sort_order", { ascending: true });

  if (mError) {
    throw new AnalysisServiceError(`Failed to fetch milestones: ${mError.message}`, 500);
  }

  const milestones: ProjectMilestoneRecord[] = (rawMilestones || []).sort((a: any, b: any) => {
    const orderA = a.sort_order ?? a.order_index ?? 0;
    const orderB = b.sort_order ?? b.order_index ?? 0;
    if (orderA !== orderB) return orderA - orderB;
    return new Date(a.created_at || 0).getTime() - new Date(b.created_at || 0).getTime();
  });

  const milestoneIds = milestones.map((m) => m.id);

  // 2. Fetch Tasks
  let tasks: ProjectTaskRecord[] = [];
  if (milestoneIds.length > 0) {
    const { data: rawTasks, error: tError } = await supabase
      .from("project_tasks")
      .select("*")
      .in("milestone_id", milestoneIds);

    if (tError) {
      throw new AnalysisServiceError(`Failed to fetch tasks: ${tError.message}`, 500);
    }
    tasks = (rawTasks || []) as ProjectTaskRecord[];
  }

  // 3. Compute Stats & Dates
  const now = new Date();
  const completedTasks = tasks.filter((t) => t.status === "completed");
  const pendingTasks = tasks.filter((t) => t.status !== "completed");
  const overdueTasks = tasks.filter((t) => {
    if (t.status === "completed") return false;
    if (!t.due_date) return false;
    return new Date(t.due_date) < now;
  });

  const totalMilestones = milestones.length;
  const completedMilestones = milestones.filter((m) => m.status === "completed");
  const totalTasks = tasks.length;
  const completedTasksCount = completedTasks.length;
  const overdueTasksCount = overdueTasks.length;
  const pendingTasksCount = pendingTasks.length;

  const progressPercentage =
    totalMilestones > 0
      ? Math.round((completedMilestones.length / totalMilestones) * 100)
      : totalTasks > 0
      ? Math.round((completedTasksCount / totalTasks) * 100)
      : 0;

  const stats = {
    total_milestones: totalMilestones,
    completed_milestones: completedMilestones.length,
    total_tasks: totalTasks,
    completed_tasks: completedTasksCount,
    overdue_tasks: overdueTasksCount,
    pending_tasks: pendingTasksCount,
    progress_percentage: progressPercentage,
  };

  // 4. Upcoming Deadlines (due within next 14 days)
  const fourteenDaysMs = 14 * 24 * 60 * 60 * 1000;
  const startOfToday = new Date();
  startOfToday.setHours(0, 0, 0, 0);
  const endOfFourteenDays = new Date(startOfToday.getTime() + fourteenDaysMs);
  endOfFourteenDays.setHours(23, 59, 59, 999);

  const upcomingDeadlines: Array<{
    type: "milestone" | "task";
    id: string;
    title: string;
    due_date: string;
    priority: string;
  }> = [];

  for (const m of milestones) {
    if (m.status !== "completed" && m.due_date) {
      const d = new Date(m.due_date);
      if (d >= startOfToday && d <= endOfFourteenDays) {
        upcomingDeadlines.push({
          type: "milestone",
          id: m.id,
          title: m.title,
          due_date: m.due_date,
          priority: (m as any).priority || "high",
        });
      }
    }
  }

  for (const t of tasks) {
    if (t.status !== "completed" && t.due_date) {
      const d = new Date(t.due_date);
      if (d >= startOfToday && d <= endOfFourteenDays) {
        upcomingDeadlines.push({
          type: "task",
          id: t.id,
          title: t.title,
          due_date: t.due_date,
          priority: t.priority || "medium",
        });
      }
    }
  }

  upcomingDeadlines.sort(
    (a, b) => new Date(a.due_date).getTime() - new Date(b.due_date).getTime()
  );

  // 5. Recent Mentor Feedback (joined with profiles)
  let recentMentorFeedback: Array<{
    id: string;
    author_name: string;
    content: string;
    created_at: string;
  }> = [];

  try {
    let feedbackQuery = supabase
      .from("milestone_feedback")
      .select(`
        id,
        project_id,
        milestone_id,
        content,
        created_at,
        author_id,
        author:author_id (
          id,
          full_name
        )
      `)
      .order("created_at", { ascending: false })
      .limit(8);

    if (milestoneIds.length > 0) {
      feedbackQuery = feedbackQuery.or(`project_id.eq.${project.id},milestone_id.in.(${milestoneIds.join(",")})`);
    } else {
      feedbackQuery = feedbackQuery.eq("project_id", project.id);
    }

    const { data: rawFeedback } = await feedbackQuery;

    if (rawFeedback && rawFeedback.length > 0) {
      recentMentorFeedback = rawFeedback.map((fb: any) => ({
        id: fb.id,
        author_name: fb.author?.full_name || "Board Mentor",
        content: fb.content,
        created_at: fb.created_at,
      }));
    } else {
      // Query fallback if author relation alias behaves differently
      let fallbackQuery = supabase
        .from("milestone_feedback")
        .select("id, project_id, milestone_id, content, created_at, author_id")
        .order("created_at", { ascending: false })
        .limit(8);

      if (milestoneIds.length > 0) {
        fallbackQuery = fallbackQuery.or(`project_id.eq.${project.id},milestone_id.in.(${milestoneIds.join(",")})`);
      } else {
        fallbackQuery = fallbackQuery.eq("project_id", project.id);
      }

      const { data: fbList } = await fallbackQuery;
      if (fbList && fbList.length > 0) {
        const authorIds = Array.from(new Set(fbList.map((f: any) => f.author_id).filter(Boolean)));
        const profileMap = new Map<string, string>();

        if (authorIds.length > 0) {
          const { data: profiles } = await supabase
            .from("profiles")
            .select("id, full_name")
            .in("id", authorIds);
          if (profiles) {
            profiles.forEach((p: any) => profileMap.set(p.id, p.full_name));
          }
        }

        recentMentorFeedback = fbList.map((fb: any) => ({
          id: fb.id,
          author_name: profileMap.get(fb.author_id) || "Board Mentor",
          content: fb.content,
          created_at: fb.created_at,
        }));
      }
    }
  } catch (fbErr) {
    console.warn("[GeminiAnalysisService] Note on mentor feedback fetch:", fbErr);
  }

  // 6. Gemini Synthesis vs Deterministic Fallback
  let summary = "";
  let keyAccomplishments: string[] = [];
  let immediateFocuses: string[] = [];

  if (isGeminiConfigured()) {
    try {
      const prompt = `You are a venture capital portfolio director and executive startup coach at BusinessBridge.
Analyze the following operational data for startup project "${project.name}" and synthesize an executive progress summary.

REAL PROJECT METRICS & DATA:
- Project Name: ${project.name}
- Stage: ${project.stage}
- Status: ${project.status}
- Milestone Stats: ${stats.completed_milestones} of ${stats.total_milestones} completed (${stats.progress_percentage}% overall progress)
- Completed Milestones: ${completedMilestones.map((m) => `"${m.title}"`).join(", ") || "None completed yet"}
- Pending Milestones: ${milestones.filter((m) => m.status !== "completed").map((m) => `"${m.title}"`).join(", ") || "None"}
- Task Stats: Total ${stats.total_tasks}, Completed ${stats.completed_tasks}, Pending ${stats.pending_tasks}, Overdue ${stats.overdue_tasks}
- Completed Tasks: ${completedTasks.slice(0, 5).map((t) => `"${t.title}"`).join(", ") || "None completed yet"}
- Overdue Tasks: ${overdueTasks.map((t) => `"${t.title}" (Due: ${t.due_date})`).join(", ") || "None"}
- Upcoming Deadlines (Next 14 Days): ${upcomingDeadlines.map((d) => `${d.type.toUpperCase()}: "${d.title}" due ${d.due_date}`).join("; ") || "None"}
- Recent Mentor Feedback: ${recentMentorFeedback.map((f) => `${f.author_name}: "${f.content}"`).join("; ") || "None"}

CRITICAL RULES:
1. NEVER fabricate, hallucinate, or assume completed milestones or tasks that are not explicitly present in the data above.
2. If zero milestones or tasks are completed, state clearly that the project is in its initial setup phase.
3. Highlight real accomplishments based solely on the actual completed items.
4. Formulate immediate focuses directly addressing overdue items, upcoming deadlines, and active milestones.
5. Provide a concise, readable progress summary (2-3 sentences) suitable for executive founders and advisory boards.

Respond with a JSON object strictly adhering to this schema:
{
  "summary": "2-3 sentence executive progress overview",
  "key_accomplishments": ["1-3 accomplishments based strictly on completed items"],
  "immediate_focuses": ["2-4 immediate focuses based on overdue items or upcoming 14-day deadlines"]
}`;

      const aiResult = await generateJSON<GeminiProgressSummaryResult>(prompt, {
        model: getGeminiModel(),
        temperature: 0.2,
        systemInstruction:
          "You are an executive startup auditor at BusinessBridge. Provide factual, concise, and non-hallucinated summaries.",
      });

      if (aiResult?.summary && typeof aiResult.summary === "string") {
        summary = aiResult.summary.trim();
        keyAccomplishments = Array.isArray(aiResult.key_accomplishments)
          ? aiResult.key_accomplishments.map((item) => String(item).trim()).filter(Boolean)
          : [];
        immediateFocuses = Array.isArray(aiResult.immediate_focuses)
          ? aiResult.immediate_focuses.map((item) => String(item).trim()).filter(Boolean)
          : [];
      }
    } catch (aiError) {
      console.warn(
        "[GeminiAnalysisService] Gemini progress summary generation failed, falling back to deterministic synthesis:",
        aiError
      );
    }
  }

  // 7. Deterministic Fallback if Gemini is unconfigured or failed
  if (!summary || keyAccomplishments.length === 0 || immediateFocuses.length === 0) {
    const fallback = buildDeterministicProgressSummary(
      project,
      stats,
      milestones,
      tasks,
      upcomingDeadlines,
      overdueTasks
    );

    summary = summary || fallback.summary;
    keyAccomplishments =
      keyAccomplishments.length > 0 ? keyAccomplishments : fallback.key_accomplishments;
    immediateFocuses =
      immediateFocuses.length > 0 ? immediateFocuses : fallback.immediate_focuses;
  }

  return {
    success: true,
    project_id: project.id,
    project_name: project.name,
    summary,
    stats,
    upcoming_deadlines: upcomingDeadlines,
    recent_mentor_feedback: recentMentorFeedback,
    key_accomplishments: keyAccomplishments,
    immediate_focuses: immediateFocuses,
  };
}

/**
 * Generates an AI-backed and heuristic risk analysis for a startup project.
 *
 * @param founderUserId The authenticated founder user ID
 * @param projectId Optional project ID; defaults to founder's active project
 * @returns RiskAnalysisResponse
 */
export async function generateRiskAnalysis(
  founderUserId: string,
  projectId?: string
): Promise<RiskAnalysisResponse> {
  const supabase = await createClient();
  const project = await fetchAuthorizedProject(founderUserId, projectId);

  // 1. Fetch Milestones
  const { data: rawMilestones, error: mError } = await supabase
    .from("project_milestones")
    .select("*")
    .eq("project_id", project.id)
    .order("sort_order", { ascending: true });

  if (mError) {
    throw new AnalysisServiceError(`Failed to fetch milestones: ${mError.message}`, 500);
  }

  const milestones: ProjectMilestoneRecord[] = (rawMilestones || []).sort((a: any, b: any) => {
    const orderA = a.sort_order ?? a.order_index ?? 0;
    const orderB = b.sort_order ?? b.order_index ?? 0;
    if (orderA !== orderB) return orderA - orderB;
    return new Date(a.created_at || 0).getTime() - new Date(b.created_at || 0).getTime();
  });

  const milestoneIds = milestones.map((m) => m.id);

  // 2. Fetch Tasks
  let tasks: ProjectTaskRecord[] = [];
  if (milestoneIds.length > 0) {
    const { data: rawTasks, error: tError } = await supabase
      .from("project_tasks")
      .select("*")
      .in("milestone_id", milestoneIds);

    if (tError) {
      throw new AnalysisServiceError(`Failed to fetch tasks: ${tError.message}`, 500);
    }
    tasks = (rawTasks || []) as ProjectTaskRecord[];
  }

  // 3. Fetch Mentor Feedback
  let feedbackList: MilestoneFeedbackRecord[] = [];
  try {
    let fbQuery = supabase
      .from("milestone_feedback")
      .select("*")
      .order("created_at", { ascending: false });

    if (milestoneIds.length > 0) {
      fbQuery = fbQuery.or(`project_id.eq.${project.id},milestone_id.in.(${milestoneIds.join(",")})`);
    } else {
      fbQuery = fbQuery.eq("project_id", project.id);
    }

    const { data: rawFeedback } = await fbQuery;
    feedbackList = (rawFeedback || []) as MilestoneFeedbackRecord[];
  } catch (fbErr) {
    console.warn("[GeminiAnalysisService] Note on feedback query:", fbErr);
  }

  // 4. Heuristic Risk Detection
  const now = new Date();

  // A. Overdue milestones (due_date < now && status !== 'completed')
  const overdueMilestones = milestones.filter((m) => {
    if (m.status === "completed") return false;
    if (!m.due_date) return false;
    return new Date(m.due_date) < now;
  });

  // B. Incomplete critical tasks (priority === 'critical' && status !== 'completed')
  const incompleteCriticalTasks = tasks.filter((t) => {
    return t.priority === "critical" && t.status !== "completed";
  });

  // C. Target Launch Date evaluation against incomplete critical/high milestones
  const targetLaunchDate: string | null =
    (project as any).target_launch_date || (project as any).launch_date || null;

  let isLaunchAtRisk = false;
  let projectedDelayDays: number | undefined = undefined;
  let launchDelayRationale = "";

  const incompleteCriticalOrHighMilestones = milestones.filter(
    (m) =>
      m.status !== "completed" &&
      ((m as any).priority === "critical" ||
        (m as any).priority === "high" ||
        overdueMilestones.some((om) => om.id === m.id))
  );

  if (targetLaunchDate) {
    const launchDate = new Date(targetLaunchDate);
    const diffDays = Math.ceil((launchDate.getTime() - now.getTime()) / (1000 * 60 * 60 * 24));

    if (launchDate < now) {
      isLaunchAtRisk = true;
      projectedDelayDays = Math.max(1, Math.abs(diffDays));
      launchDelayRationale = `Target launch date (${targetLaunchDate}) elapsed ${projectedDelayDays} day(s) ago with ${incompleteCriticalOrHighMilestones.length} critical or high-priority milestone(s) still incomplete.`;
    } else if (overdueMilestones.length > 0 || incompleteCriticalTasks.length > 0) {
      isLaunchAtRisk = true;
      projectedDelayDays = Math.min(
        60,
        overdueMilestones.length * 7 + incompleteCriticalTasks.length * 3
      );
      launchDelayRationale = `Target launch is scheduled in ${diffDays} day(s), but ${overdueMilestones.length} overdue milestone(s) and ${incompleteCriticalTasks.length} incomplete critical task(s) threaten timely deployment.`;
    } else if (diffDays <= 14 && incompleteCriticalOrHighMilestones.length > 2) {
      isLaunchAtRisk = true;
      projectedDelayDays = 14;
      launchDelayRationale = `Target launch is approaching in ${diffDays} days, while ${incompleteCriticalOrHighMilestones.length} critical deliverables remain in progress.`;
    } else {
      isLaunchAtRisk = false;
      projectedDelayDays = 0;
      launchDelayRationale = `Target launch date (${targetLaunchDate}) is currently on schedule with ${diffDays} day(s) remaining.`;
    }
  } else {
    if (overdueMilestones.length > 0 || incompleteCriticalTasks.length > 0) {
      isLaunchAtRisk = true;
      projectedDelayDays = overdueMilestones.length * 7 + incompleteCriticalTasks.length * 3;
      launchDelayRationale = `No target launch date is configured. However, ${overdueMilestones.length} overdue milestone(s) and ${incompleteCriticalTasks.length} incomplete critical task(s) jeopardize execution momentum.`;
    } else {
      isLaunchAtRisk = false;
      projectedDelayDays = 0;
      launchDelayRationale =
        "No target launch date has been set. Current active milestones and critical tasks are executing without overdue backlogs.";
    }
  }

  // D. Unaddressed mentor feedback (feedback with status 'active' or on overdue/blocked items)
  const overdueMilestoneIdSet = new Set(overdueMilestones.map((m) => m.id));
  const unaddressedFeedback = feedbackList.filter((fb: any) => {
    const isActive = fb.status === "active";
    const isOnOverdueMilestone = overdueMilestoneIdSet.has(fb.milestone_id);
    const isConcernOrBlocker =
      fb.feedback_type === "concern" ||
      fb.feedback_type === "blocking" ||
      fb.feedback_type === "critical";
    return isActive || isOnOverdueMilestone || isConcernOrBlocker;
  });

  // Build Deterministic Risk Items
  const deterministicRisks: RiskItem[] = [];

  // 1. Overdue Milestones Risk
  if (overdueMilestones.length > 0) {
    const references = overdueMilestones.map((m) => ({
      type: "milestone" as const,
      id: m.id,
      title: m.title,
    }));
    const severity: "low" | "medium" | "high" =
      overdueMilestones.length >= 2 ? "high" : "medium";

    deterministicRisks.push({
      id: "risk-overdue-milestones",
      title: `${overdueMilestones.length} Milestone(s) Overdue`,
      description: `Milestone(s) ${overdueMilestones
        .map((m) => `"${m.title}"`)
        .join(", ")} have exceeded their scheduled target completion dates.`,
      severity,
      category: "overdue_milestone",
      supporting_references: references,
      suggested_mitigation:
        "Re-scope deliverable requirements with your advisory board and update milestone target dates in the Business Journey Tracker.",
    });
  }

  // 2. Incomplete Critical Tasks Risk
  if (incompleteCriticalTasks.length > 0) {
    const references = incompleteCriticalTasks.map((t) => ({
      type: "task" as const,
      id: t.id,
      title: t.title,
    }));
    const hasOverdueCritical = incompleteCriticalTasks.some(
      (t) => t.due_date && new Date(t.due_date) < now
    );

    deterministicRisks.push({
      id: "risk-incomplete-critical-tasks",
      title: `${incompleteCriticalTasks.length} Incomplete Critical Task(s)`,
      description: `High-priority blocker task(s) ${incompleteCriticalTasks
        .slice(0, 3)
        .map((t) => `"${t.title}"`)
        .join(", ")} remain uncompleted${hasOverdueCritical ? ", with overdue deadlines" : ""}.`,
      severity: hasOverdueCritical || incompleteCriticalTasks.length >= 3 ? "high" : "medium",
      category: "incomplete_critical_task",
      supporting_references: references,
      suggested_mitigation:
        "Prioritize team focus on resolving these critical path tasks immediately before commencing lower-priority tasks.",
    });
  }

  // 3. Launch Delay Risk
  if (isLaunchAtRisk) {
    const launchReferences: Array<{
      type: "milestone" | "task" | "feedback" | "project";
      id: string;
      title: string;
    }> = [{ type: "project", id: project.id, title: project.name }];

    overdueMilestones.slice(0, 2).forEach((m) => {
      launchReferences.push({ type: "milestone", id: m.id, title: m.title });
    });
    incompleteCriticalTasks.slice(0, 2).forEach((t) => {
      launchReferences.push({ type: "task", id: t.id, title: t.title });
    });

    deterministicRisks.push({
      id: "risk-launch-delay",
      title: targetLaunchDate
        ? "Target Launch Date Slipped or at Risk"
        : "Operational Delivery Velocity Risk",
      description: launchDelayRationale,
      severity:
        (projectedDelayDays && projectedDelayDays > 14) || overdueMilestones.length >= 2
          ? "high"
          : "medium",
      category: "launch_delay",
      supporting_references: launchReferences,
      suggested_mitigation:
        "Review MVP feature scope with your advisory board mentors and adjust non-essential milestones to safeguard launch readiness.",
    });
  }

  // 4. Unaddressed Mentor Feedback Risk
  if (unaddressedFeedback.length > 0) {
    const references = unaddressedFeedback.slice(0, 4).map((fb) => ({
      type: "feedback" as const,
      id: fb.id,
      title: (fb.content || "").slice(0, 45) + (fb.content && fb.content.length > 45 ? "..." : ""),
    }));

    deterministicRisks.push({
      id: "risk-unaddressed-feedback",
      title: `${unaddressedFeedback.length} Actionable Advisory Feedback Item(s)`,
      description:
        "Mentor feedback on active or overdue milestones requires review and implementation by the founder.",
      severity: "medium",
      category: "unaddressed_feedback",
      supporting_references: references,
      suggested_mitigation:
        "Acknowledge advisor comments in the Virtual Boardroom and convert strategic recommendations into concrete tasks.",
    });
  }

  // 5. Default healthy operational state if no risks detected
  if (deterministicRisks.length === 0) {
    deterministicRisks.push({
      id: "risk-operational-baseline",
      title: "Healthy Milestone Cadence",
      description: `Project "${project.name}" has no overdue milestones or critical task backlogs. Execution is progressing steadily.`,
      severity: "low",
      category: "operational",
      supporting_references: [{ type: "project", id: project.id, title: project.name }],
      suggested_mitigation:
        "Maintain current sprint discipline and schedule regular boardroom reviews to preempt stage bottlenecks.",
    });
  }

  // Calculate overall risk level
  let overallRiskLevel: "low" | "medium" | "high" = "low";
  if (deterministicRisks.some((r) => r.severity === "high")) {
    overallRiskLevel = "high";
  } else if (deterministicRisks.some((r) => r.severity === "medium")) {
    overallRiskLevel = "medium";
  }

  let finalRisks: RiskItem[] = deterministicRisks;
  let finalLaunchDelayRisk = {
    target_launch_date: targetLaunchDate,
    is_at_risk: isLaunchAtRisk,
    projected_delay_days: projectedDelayDays,
    rationale: launchDelayRationale,
  };

  // 5. Gemini AI Evaluation & Refinement
  if (isGeminiConfigured()) {
    try {
      const prompt = `You are a venture capital risk auditor and startup advisory partner at BusinessBridge.
Perform an AI Risk Analysis on startup project "${project.name}" based strictly on current operational data.

PROJECT AUDIT DATA:
- Project Name: ${project.name}
- Stage: ${project.stage}
- Target Launch Date: ${targetLaunchDate || "Not explicitly scheduled"}
- Overdue Milestones (${overdueMilestones.length}): ${
        overdueMilestones
          .map((m) => `[ID: ${m.id}] "${m.title}" (Due: ${m.due_date})`)
          .join("; ") || "None"
      }
- Incomplete Critical Tasks (${incompleteCriticalTasks.length}): ${
        incompleteCriticalTasks
          .map((t) => `[ID: ${t.id}] "${t.title}" (Due: ${t.due_date || "No due date"})`)
          .join("; ") || "None"
      }
- Launch Delay Status: ${launchDelayRationale}
- Unaddressed Mentor Feedback (${unaddressedFeedback.length}): ${
        unaddressedFeedback
          .map((f) => `[ID: ${f.id}] "${f.content}"`)
          .join("; ") || "None"
      }

CRITICAL RULES:
1. NEVER fabricate or invent risks, tasks, or milestones that are not directly present in the project data.
2. Every risk item must reference actual items from the provided data in "supporting_references" using their exact IDs and titles.
3. Categorize severity strictly: "high" (blocking launch or severe backlog), "medium" (concerning friction), or "low" (minor operational note).
4. Category must be one of: "overdue_milestone", "incomplete_critical_task", "launch_delay", "unaddressed_feedback", "operational".
5. Provide actionable, practical mitigation advice citing actual project items.
6. If there are no overdue items or bottlenecks, set overall_risk_level to "low" and report a healthy operational advisory.

Respond with a JSON object strictly matching this schema:
{
  "overall_risk_level": "low" | "medium" | "high",
  "risks": [
    {
      "id": "risk-identifier",
      "title": "Clear concise risk name",
      "description": "Factual explanation referencing actual project items",
      "severity": "low" | "medium" | "high",
      "category": "overdue_milestone" | "incomplete_critical_task" | "launch_delay" | "unaddressed_feedback" | "operational",
      "supporting_references": [
        {
          "type": "milestone" | "task" | "feedback" | "project",
          "id": "id-string",
          "title": "title-string"
        }
      ],
      "suggested_mitigation": "Practical, actionable mitigation advice"
    }
  ],
  "launch_delay_risk": {
    "is_at_risk": true,
    "projected_delay_days": 14,
    "rationale": "Clear rationale on launch timeline feasibility"
  }
}`;

      const aiRiskResult = await generateJSON<GeminiRiskResult>(prompt, {
        model: getGeminiModel(),
        temperature: 0.2,
        systemInstruction:
          "You are a rigorous startup risk analyst at BusinessBridge. All assessments must be grounded in real milestone, task, and feedback data without fabrication.",
      });

      if (aiRiskResult && Array.isArray(aiRiskResult.risks) && aiRiskResult.risks.length > 0) {
        const validatedRisks: RiskItem[] = aiRiskResult.risks.map((r, idx) => {
          const category = [
            "overdue_milestone",
            "incomplete_critical_task",
            "launch_delay",
            "unaddressed_feedback",
            "operational",
          ].includes(r.category)
            ? r.category
            : "operational";

          const severity = ["low", "medium", "high"].includes(r.severity)
            ? r.severity
            : "medium";

          const supportingReferences = Array.isArray(r.supporting_references)
            ? r.supporting_references.map((ref) => ({
                type: (["milestone", "task", "feedback", "project"].includes(ref.type)
                  ? ref.type
                  : "project") as "milestone" | "task" | "feedback" | "project",
                id: String(ref.id || project.id),
                title: String(ref.title || project.name),
              }))
            : [{ type: "project" as const, id: project.id, title: project.name }];

          return {
            id: r.id || `ai-risk-${idx + 1}`,
            title: String(r.title || "Identified Project Risk"),
            description: String(r.description || ""),
            severity,
            category,
            supporting_references: supportingReferences,
            suggested_mitigation: String(
              r.suggested_mitigation || "Review with advisory board mentors."
            ),
          };
        });

        finalRisks = validatedRisks;

        if (["low", "medium", "high"].includes(aiRiskResult.overall_risk_level)) {
          overallRiskLevel = aiRiskResult.overall_risk_level;
        }

        if (aiRiskResult.launch_delay_risk) {
          finalLaunchDelayRisk = {
            target_launch_date: targetLaunchDate,
            is_at_risk: Boolean(aiRiskResult.launch_delay_risk.is_at_risk ?? isLaunchAtRisk),
            projected_delay_days:
              typeof aiRiskResult.launch_delay_risk.projected_delay_days === "number"
                ? aiRiskResult.launch_delay_risk.projected_delay_days
                : projectedDelayDays,
            rationale:
              aiRiskResult.launch_delay_risk.rationale || launchDelayRationale,
          };
        }
      }
    } catch (aiError) {
      console.warn(
        "[GeminiAnalysisService] Gemini risk analysis failed, utilizing heuristic assessment:",
        aiError
      );
    }
  }

  return {
    success: true,
    project_id: project.id,
    project_name: project.name,
    overall_risk_level: overallRiskLevel,
    is_ai_assessment: true,
    assessment_disclaimer: RISK_ASSESSMENT_DISCLAIMER,
    risks: finalRisks,
    launch_delay_risk: finalLaunchDelayRisk,
  };
}

/**
 * Deterministic helper to synthesize progress summary when Gemini is unconfigured or fails.
 */
function buildDeterministicProgressSummary(
  project: StartupProjectRecord,
  stats: {
    total_milestones: number;
    completed_milestones: number;
    total_tasks: number;
    completed_tasks: number;
    overdue_tasks: number;
    pending_tasks: number;
    progress_percentage: number;
  },
  milestones: ProjectMilestoneRecord[],
  tasks: ProjectTaskRecord[],
  upcomingDeadlines: Array<{
    type: "milestone" | "task";
    id: string;
    title: string;
    due_date: string;
    priority: string;
  }>,
  overdueTasks: ProjectTaskRecord[]
): { summary: string; key_accomplishments: string[]; immediate_focuses: string[] } {
  let summary = "";
  if (stats.total_milestones === 0) {
    summary = `Project "${project.name}" has been initialized in the ${project.stage} stage. Execution milestones and tasks should be mapped out to begin tracking operational progress.`;
  } else if (stats.completed_milestones === stats.total_milestones) {
    summary = `Project "${project.name}" has achieved 100% milestone completion across all ${stats.total_milestones} milestones. The venture is positioned for transition to the subsequent operational stage.`;
  } else if (stats.completed_milestones > 0) {
    summary = `Project "${project.name}" is ${stats.progress_percentage}% complete, with ${stats.completed_milestones} of ${stats.total_milestones} milestones achieved and ${stats.completed_tasks} completed task(s). ${
      stats.overdue_tasks > 0
        ? `Immediate focus is required to resolve ${stats.overdue_tasks} overdue task(s).`
        : "Execution is currently progressing on schedule."
    }`;
  } else {
    summary = `Project "${project.name}" is active in the ${project.stage} stage with ${stats.total_milestones} milestone(s) outlined. Setup is underway with ${stats.completed_tasks} of ${stats.total_tasks} task(s) finalized.`;
  }

  const completedMilestoneTitles = milestones
    .filter((m) => m.status === "completed")
    .map((m) => `Completed milestone: ${m.title}`);
  const completedTaskTitles = tasks
    .filter((t) => t.status === "completed")
    .slice(0, 3)
    .map((t) => `Finished task: ${t.title}`);

  let key_accomplishments = [...completedMilestoneTitles, ...completedTaskTitles];
  if (key_accomplishments.length === 0) {
    key_accomplishments = [
      `Initialized operational roadmap for "${project.name}" at ${project.stage} stage`,
      `Configured ${stats.total_milestones} strategic milestone(s) in the Business Journey Tracker`,
    ];
  }

  const immediate_focuses: string[] = [];
  if (overdueTasks.length > 0) {
    immediate_focuses.push(
      `Resolve ${overdueTasks.length} overdue task(s): ${overdueTasks
        .slice(0, 2)
        .map((t) => `"${t.title}"`)
        .join(", ")}`
    );
  }

  if (upcomingDeadlines.length > 0) {
    const nextDeadline = upcomingDeadlines[0];
    immediate_focuses.push(
      `Deliver ${nextDeadline.type} "${nextDeadline.title}" before ${new Date(
        nextDeadline.due_date
      ).toLocaleDateString()}`
    );
  }

  const activeMilestones = milestones.filter(
    (m) => m.status === "in_progress" || m.status === "not_started"
  );
  if (activeMilestones.length > 0 && immediate_focuses.length < 3) {
    immediate_focuses.push(`Advance deliverable milestone: "${activeMilestones[0].title}"`);
  }

  if (immediate_focuses.length === 0) {
    immediate_focuses.push("Conduct periodic milestone review with advisory board mentors.");
  }

  return { summary, key_accomplishments, immediate_focuses };
}

